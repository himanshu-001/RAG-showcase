"""
Pydantic data models for structured request and response validation
across FastAPI and the RAG engine.
"""

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class RetrievedSource(BaseModel):
    """Structured information for a retrieved context chunk."""
    rank: int = Field(..., description="Rank in retrieval order (1-indexed)")
    chunk_id: int = Field(..., description="Sequential chunk identifier")
    source: str = Field(..., description="Document source or filename")
    content: str = Field(..., description="Text content of the retrieved chunk")
    distance: float = Field(..., description="FAISS L2 distance; lower is more relevant")
    similarity_pct: float = Field(..., description="Monotonic L2-derived relevance score (0-100%), not cosine similarity")
    char_count: int = Field(..., description="Character length of chunk")


class ToolCallRecord(BaseModel):
    """Record of a tool invoked by the LLM."""
    tool: str = Field(..., description="Name of the tool invoked")
    args: Dict[str, Any] = Field(default_factory=dict, description="Arguments passed to the tool")
    output: str = Field(..., description="Result returned by the tool execution")


class ChatRequest(BaseModel):
    """Request payload for sending a chat query to the RAG pipeline."""
    question: str = Field(..., description="User question to answer using RAG")
    session_id: Optional[str] = Field("default", description="Session identifier for multi-turn conversational history")
    model: Optional[str] = Field("gemini-3.5-flash-lite", description="Model name (e.g. gemini-3.5-flash-lite, gemma-4-31b-it, or local Ollama qwen2.5:0.5b)")
    temperature: Optional[float] = Field(0.0, ge=0.0, le=1.0, description="Sampling temperature")
    k: Optional[int] = Field(4, ge=1, le=10, description="Number of top context chunks to retrieve")
    strict_mode: Optional[bool] = Field(True, description="Strictly ground answers to retrieved context")
    min_relevance_pct: Optional[float] = Field(25.0, ge=0.0, le=100.0, description="Minimum L2-derived relevance score required in strict mode")
    use_tool_calling: Optional[bool] = Field(False, description="Enable agentic tool calling (bind_tools)")


class RAGResponse(BaseModel):
    """Structured response payload returned by the RAG engine."""
    question: str = Field(..., description="Original user question")
    answer: str = Field(..., description="Clean, grounded answer text generated by the model")
    thinking: Optional[str] = Field(None, description="Model internal reasoning/thinking process if present")
    session_id: str = Field(..., description="Session identifier")
    sources: List[RetrievedSource] = Field(default_factory=list, description="Retrieved context chunks with similarity metrics")
    prompt: str = Field(default="", description="Full augmented prompt sent to the LLM")
    tool_calls: List[ToolCallRecord] = Field(default_factory=list, description="Tool execution records")
    model_used: str = Field(..., description="Model name used for generation")


class RetrieveRequest(BaseModel):
    """Request payload for querying the vector store directly."""
    query: str = Field(..., description="Query to search against indexed knowledge base")
    k: Optional[int] = Field(4, ge=1, le=10, description="Number of top chunks to return")


class RetrieveResponse(BaseModel):
    """Structured response payload for retrieval queries."""
    query: str = Field(..., description="Original query searched")
    results: List[RetrievedSource] = Field(..., description="List of retrieved chunks with similarity metrics")


class ChunkInfo(BaseModel):
    """Details of a single chunk stored in the vector store."""
    chunk_id: int = Field(..., description="Sequential chunk identifier")
    source: str = Field(..., description="Source document name")
    char_count: int = Field(..., description="Character count of chunk")
    content: str = Field(..., description="Text content of chunk")


class ChunksResponse(BaseModel):
    """Structured response payload listing all indexed chunks."""
    chunks: List[ChunkInfo] = Field(..., description="All chunks currently indexed in vector store")
    total: int = Field(..., description="Total count of chunks")


class HealthResponse(BaseModel):
    """Structured health check response."""
    status: str = Field(..., description="Health status (e.g. healthy)")
    rag_ready: bool = Field(..., description="Whether vector store and pipeline are initialized")
    test_mode: bool = Field(..., description="Whether running in offline test mode")
    indexed_chunks: int = Field(..., description="Number of indexed chunks")


class SessionMessage(BaseModel):
    """A single turn in the conversational session history."""
    role: str = Field(..., description="'user' or 'assistant'")
    content: str = Field(..., description="Message text content")
    timestamp: float = Field(..., description="Timestamp of the message")
    thinking: Optional[str] = Field(None, description="Reasoning/thinking process if assistant message")
    sources: List[RetrievedSource] = Field(default_factory=list, description="Source chunks if assistant message")
    prompt: Optional[str] = Field(default="", description="Augmented prompt if assistant message")
    tool_calls: List[ToolCallRecord] = Field(default_factory=list, description="Tool calls if assistant message")


class SessionHistoryResponse(BaseModel):
    """Structured response payload containing the full conversation history for a session."""
    session_id: str = Field(..., description="Session identifier")
    messages: List[SessionMessage] = Field(..., description="Ordered list of conversation messages")


class SessionsListResponse(BaseModel):
    """Structured response listing all active session IDs."""
    sessions: List[str] = Field(..., description="List of active session IDs")


class KnowledgeSourceInfo(BaseModel):
    """Information regarding a persistent knowledge base source."""
    id: str = Field(..., description="Unique source identifier")
    name: str = Field(..., description="Display name or original source filename/URL")
    source_type: str = Field(..., description="Source type: 'file', 'url', or 'placeholder'")
    char_count: int = Field(..., description="Total character count in source")
    created_at: float = Field(..., description="Unix timestamp when added")
    updated_at: float = Field(..., description="Unix timestamp when updated")
    meta: Dict[str, Any] = Field(default_factory=dict, description="Metadata dictionary")


class KnowledgeSourcesResponse(BaseModel):
    """Response containing active knowledge base status and list of sources."""
    is_placeholder: bool = Field(..., description="Whether the knowledge base is using the default company_policy.md placeholder")
    sources: List[KnowledgeSourceInfo] = Field(..., description="List of active knowledge sources")
    total_sources: int = Field(..., description="Number of active sources")
    total_chunks: int = Field(..., description="Number of indexed chunks in the vector store")


class AddUrlSourceRequest(BaseModel):
    """Request payload for ingesting a JSON/NDJSON endpoint URL."""
    url: str = Field(..., description="HTTP/HTTPS URL of the JSON or NDJSON endpoint")
